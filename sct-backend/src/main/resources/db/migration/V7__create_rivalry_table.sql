-- intensity:
-- 1 = minor
-- 2 = standard 
-- 3 = marquee

CREATE TABLE rivalry (
    id BIGSERIAL PRIMARY KEY,
    league VARCHAR(10) NOT NULL,
    team_a VARCHAR(100) NOT NULL,
    team_b VARCHAR(100) NOT NULL,
    intensity INT NOT NULL CHECK (intensity BETWEEN 1 AND 3),
    note VARCHAR(100),
    CONSTRAINT uq_rivalry_pair UNIQUE (league, team_a, team_b),
    CONSTRAINT ck_rivalry_order CHECK (team_a < team_b)
);

